const server = createServer((req, res) => {
  const url = new URL(req.url || '/', `http://localhost:${PORT}`)

  if (url.pathname === '/' || url.pathname === '/index.html') {
    res.writeHead(200, { 'Content-Type': 'text/html' })
    res.end(generateHTML())
    return
  }

  if (url.pathname === '/api/statements' && req.method === 'GET') {
    res.writeHead(200, { 'Content-Type': 'application/json' })
    res.end(JSON.stringify(statements))
    return
  }

  if (url.pathname.startsWith('/api/statements/') && req.method === 'POST') {
    const id = url.pathname.replace('/api/statements/', '')
    const statement = statements.find((statement) => statement.id === id)

    if (!statement) {
      res.writeHead(404)
      res.end('Not found')
      return
    }

    let body = ''
    req.on('data', (chunk) => (body += chunk))
    req.on('end', () => {
      const data: StatementData = JSON.parse(body)
      statement.data = data

      const jsonPath = join(BASE_PATH, statement.jsonPath)
      writeFileSync(jsonPath, JSON.stringify(data, null, 2) + '\n')

      computeDateValidation(statements)

      res.writeHead(200, { 'Content-Type': 'application/json' })
      res.end(JSON.stringify({ ok: true, dateValidation: statement.dateValidation }))
    })
    return
  }

  if (url.pathname === '/api/ocr-extract' && req.method === 'POST') {
    if (!ANTHROPIC_API_KEY) {
      res.writeHead(200, { 'Content-Type': 'application/json' })
      res.end(JSON.stringify({ error: 'ANTHROPIC_API_KEY not set' }))
      return
    }

    let body = ''
    req.on('data', (chunk) => (body += chunk))
    req.on('end', async () => {
      try {
        const { statementId, image, signedOffFields = [] } = JSON.parse(body)
        const statement = statements.find((s) => s.id === statementId)

        if (!statement) {
          res.writeHead(200, { 'Content-Type': 'application/json' })
          res.end(JSON.stringify({ error: 'Statement not found' }))
          return
        }

        const base64Data = image.replace(/^data:image\/\w+;base64,/, '')

        const signedOffData: Record<string, unknown> = {}
        for (const field of signedOffFields) {
          if (field === 'transactions') {
            signedOffData[field] = statement.data.transactions
          } else if (statement.data.summary[field as keyof StatementSummary] !== undefined) {
            signedOffData[field] = statement.data.summary[field as keyof StatementSummary]
          }
        }

        const signedOffInstructions =
          Object.keys(signedOffData).length > 0
            ? `\n\nIMPORTANT: The following fields have been verified by the user. You MUST use these EXACT values and NOT extract them from the image:\n${Object.entries(
                signedOffData,
              )
                .map(([field, value]) => `- ${field}: ${JSON.stringify(value)}`)
                .join('\n')}`
            : ''

        const requestBody = JSON.stringify({
          model: 'claude-sonnet-4-20250514',
          max_tokens: 4096,
          messages: [
            {
              role: 'user',
              content: [
                {
                  type: 'image',
                  source: {
                    type: 'base64',
                    media_type: 'image/png',
                    data: base64Data,
                  },
                },
                {
                  type: 'text',
                  text: `Extract bank statement data from this image and return it as JSON.${signedOffInstructions}

Return ONLY valid JSON with this exact structure:
{
  "summary": {
    "statementDate": "YYYY-MM-DD" or null,
    "statementNumber": number or null,
    "pageNumber": "string" or null,
    "openingBalance": number or null,
    "totalMoneyOut": number or null,
    "totalMoneyIn": number or null,
    "closingBalance": number or null
  },
  "transactions": [
    {
      "date": "YYYY-MM-DD" or null,
      "description": "string" or null,
      "moneyOut": number or null,
      "moneyIn": number or null,
      "balance": number or null
    }
  ]
}

Rules:
- Dates MUST be in YYYY-MM-DD format
- Amounts must be plain numbers (e.g. 50.00 not £50.00)
- Use null for values you cannot find
- Extract ALL transactions you can see
- Return ONLY the JSON, no other text`,
                },
              ],
            },
          ],
        })

        const options = {
          hostname: 'api.anthropic.com',
          path: '/v1/messages',
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'x-api-key': ANTHROPIC_API_KEY,
            'anthropic-version': '2023-06-01',
          },
        }

        const apiReq = httpsRequest(options, (apiRes) => {
          let data = ''
          apiRes.on('data', (chunk) => (data += chunk))
          apiRes.on('end', () => {
            try {
              const response = JSON.parse(data)
              if (response.error) {
                res.writeHead(200, { 'Content-Type': 'application/json' })
                res.end(JSON.stringify({ error: response.error.message || 'API error' }))
                return
              }

              const content = response.content?.[0]?.text || ''
              const jsonMatch = content.match(/\{[\s\S]*\}/)
              if (!jsonMatch) {
                res.writeHead(200, { 'Content-Type': 'application/json' })
                res.end(JSON.stringify({ error: 'No JSON in response' }))
                return
              }

              const extracted = JSON.parse(jsonMatch[0])

              for (const field of signedOffFields) {
                if (field === 'transactions') {
                  extracted.transactions = statement.data.transactions
                } else if (field in extracted.summary) {
                  extracted.summary[field] = statement.data.summary[field as keyof StatementSummary]
                }
              }

              statement.data.summary = extracted.summary
              statement.data.transactions = extracted.transactions

              const summary = statement.data.summary
              let totalIn = 0
              let totalOut = 0
              for (const transaction of statement.data.transactions) {
                if (transaction.moneyIn !== null) totalIn += transaction.moneyIn
                if (transaction.moneyOut !== null) totalOut += transaction.moneyOut
              }
              const calculatedClosing =
                summary.openingBalance !== null
                  ? Math.round((summary.openingBalance + totalIn - totalOut) * 100) / 100
                  : null
              const difference =
                calculatedClosing !== null && summary.closingBalance !== null
                  ? Math.round((calculatedClosing - summary.closingBalance) * 100) / 100
                  : null
              statement.data.validation = {
                valid: difference !== null && Math.abs(difference) < 0.02,
                calculatedClosing,
                difference,
              }

              const jsonPath = join(BASE_PATH, statement.jsonPath)
              writeFileSync(jsonPath, JSON.stringify(statement.data, null, 2) + '\n')

              computeDateValidation(statements)

              const usage = response.usage || {}
              const inputCost = (usage.input_tokens || 0) * 0.000003
              const outputCost = (usage.output_tokens || 0) * 0.000015
              const totalCost = inputCost + outputCost

              res.writeHead(200, { 'Content-Type': 'application/json' })
              res.end(
                JSON.stringify({
                  ok: true,
                  data: statement.data,
                  dateValidation: statement.dateValidation,
                  cost: totalCost.toFixed(4),
                }),
              )
            } catch (err) {
              res.writeHead(200, { 'Content-Type': 'application/json' })
              res.end(JSON.stringify({ error: 'Failed to parse response: ' + (err as Error).message }))
            }
          })
        })

        apiReq.on('error', (err) => {
          res.writeHead(200, { 'Content-Type': 'application/json' })
          res.end(JSON.stringify({ error: 'API request failed: ' + err.message }))
        })

        apiReq.write(requestBody)
        apiReq.end()
      } catch (err) {
        res.writeHead(200, { 'Content-Type': 'application/json' })
        res.end(JSON.stringify({ error: 'Failed to process request: ' + (err as Error).message }))
      }
    })
    return
  }

  if (url.pathname.startsWith('/file/')) {
    const filePath = join(BASE_PATH, url.pathname.replace('/file/', ''))
    if (existsSync(filePath) && statSync(filePath).isFile()) {
      res.writeHead(200, { 'Content-Type': getMimeType(filePath) })
      res.end(readFileSync(filePath))
      return
    }
  }

  res.writeHead(404)
  res.end('Not found')
})

