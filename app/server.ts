const loadStatements = (): Statement[] => {
  const statements: Statement[] = []

  if (!existsSync(BASE_PATH)) return statements

  const sourceExts = ['.jpg', '.jpeg', '.pdf', '.png']
  const allFiles = readdirSync(BASE_PATH)

  const sourceFiles = allFiles.filter((filename) => sourceExts.some((ext) => filename.endsWith(ext)))

  for (const sourceFile of sourceFiles) {
    const match = sourceFile.match(/^([a-z]+)-(\d+)\.(jpg|jpeg|pdf|png)$/i)
    if (!match) continue

    const [, account, num] = match
    const jsonFilename = `${account}-${num}.json`
    const jsonFullPath = join(BASE_PATH, jsonFilename)

    if (!existsSync(jsonFullPath)) {
      const emptyData = createEmptyStatementData()
      writeFileSync(jsonFullPath, JSON.stringify(emptyData, null, 2) + '\n')
      console.log(`Created empty JSON for ${sourceFile}`)
    }
  }

  const jsonFiles = readdirSync(BASE_PATH)
    .filter((filename) => filename.match(/^[a-z]+-\d+\.json$/i))
    .sort((fileA, fileB) => {
      const matchA = fileA.match(/^([a-z]+)-(\d+)\.json$/i)
      const matchB = fileB.match(/^([a-z]+)-(\d+)\.json$/i)
      if (!matchA || !matchB) return 0
      const accountCompare = matchA[1].localeCompare(matchB[1])
      if (accountCompare !== 0) return accountCompare
      return parseInt(matchA[2]) - parseInt(matchB[2])
    })

  for (const jsonFile of jsonFiles) {
    const match = jsonFile.match(/^([a-z]+)-(\d+)\.json$/i)
    if (!match) continue
    const [, account, num] = match
    const jsonFullPath = join(BASE_PATH, jsonFile)

    let sourcePath = ''
    for (const ext of sourceExts) {
      const testPath = join(BASE_PATH, `${account}-${num}${ext}`)
      if (existsSync(testPath)) {
        sourcePath = `${account}-${num}${ext}`
        break
      }
    }

    const rawData = JSON.parse(readFileSync(jsonFullPath, 'utf-8'))

    let needsSave = false

    if ('text' in rawData) {
      delete rawData.text
      needsSave = true
    }
    if ('ocrText' in rawData) {
      delete rawData.ocrText
      needsSave = true
    }
    if ('textTemplate' in rawData) {
      delete rawData.textTemplate
      needsSave = true
    }
    if (rawData.meta && 'signedOff' in rawData.meta) {
      delete rawData.meta.signedOff
      needsSave = true
    }
    if (rawData.meta && 'notes' in rawData.meta) {
      delete rawData.meta.notes
      needsSave = true
    }
    let data: StatementData
    if (!('//' in rawData)) {
      data = {
        '//': 'Generated by co-op-statement-digitiser',
        ...rawData,
      }
      needsSave = true
    } else {
      data = rawData
    }

    if (needsSave) {
      writeFileSync(jsonFullPath, JSON.stringify(data, null, 2) + '\n')
    }

    statements.push({
      id: `${account}-${num}`,
      account,
      statementNumber: num,
      sourcePath,
      jsonPath: jsonFile,
      data,
      dateValidation: { valid: true, issues: [] },
    })
  }

  return statements
}

const addMissingStatements = (statements: Statement[]): void => {
  const accounts = [...new Set(statements.map((s) => s.account))]

  for (const account of accounts) {
    const accountStatements = statements.filter((s) => s.account === account)
    const existingNumbers = accountStatements.map((s) => parseInt(s.statementNumber))
    const maxNumber = Math.max(...existingNumbers)
    const minNumber = Math.min(...existingNumbers)

    for (let num = minNumber; num <= maxNumber; num++) {
      if (!existingNumbers.includes(num)) {
        const paddedNum = String(num).padStart(3, '0')
        statements.push({
          id: `${account}-${paddedNum}`,
          account,
          statementNumber: paddedNum,
          sourcePath: '',
          jsonPath: '',
          data: createEmptyStatementData(),
          dateValidation: { valid: true, issues: [] },
          missing: true,
        })
      }
    }
  }

  statements.sort((a, b) => {
    const accountCompare = a.account.localeCompare(b.account)
    if (accountCompare !== 0) return accountCompare
    return parseInt(a.statementNumber) - parseInt(b.statementNumber)
  })
}

const computeDateValidation = (statements: Statement[]): void => {
  const accounts = [...new Set(statements.map((s) => s.account))]

  for (const account of accounts) {
    const accountStatements = statements
      .filter((s) => s.account === account)
      .sort((a, b) => parseInt(a.statementNumber) - parseInt(b.statementNumber))

    for (let i = 0; i < accountStatements.length; i++) {
      const stmt = accountStatements[i]
      const prevStmt = i > 0 ? accountStatements[i - 1] : null

      const issues: DateValidationIssue[] = []
      const statementDate = stmt.data.summary.statementDate ? new Date(stmt.data.summary.statementDate) : null
      const prevStatementDate = prevStmt?.data.summary.statementDate
        ? new Date(prevStmt.data.summary.statementDate)
        : null

      for (let t = 0; t < stmt.data.transactions.length; t++) {
        const tx = stmt.data.transactions[t]
        if (!tx.date) continue

        const txDate = new Date(tx.date)

        if (statementDate && txDate > statementDate) {
          issues.push({
            transactionIndex: t,
            transactionDate: tx.date,
            description: tx.description || '',
            issue: 'after_statement',
            referenceDate: stmt.data.summary.statementDate!,
          })
        }

        if (prevStatementDate && txDate < prevStatementDate) {
          issues.push({
            transactionIndex: t,
            transactionDate: tx.date,
            description: tx.description || '',
            issue: 'before_previous',
            referenceDate: prevStmt!.data.summary.statementDate!,
          })
        }
      }

      stmt.dateValidation = {
        valid: issues.length === 0,
        issues,
      }
    }
  }
}

