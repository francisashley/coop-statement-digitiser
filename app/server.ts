const getMimeType = (path: string): string => {
  const ext = extname(path).toLowerCase()
  const types: Record<string, string> = {
    '.html': 'text/html',
    '.js': 'application/javascript',
    '.css': 'text/css',
    '.json': 'application/json',
    '.png': 'image/png',
    '.jpg': 'image/jpeg',
    '.jpeg': 'image/jpeg',
    '.txt': 'text/plain',
    '.pdf': 'application/pdf',
  }
  return types[ext] || 'application/octet-stream'
}

