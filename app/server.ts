interface Transaction {
  date: string | null
  description: string | null
  moneyOut: number | null
  moneyIn: number | null
  balance: number | null
}

interface StatementSummary {
  statementDate: string | null
  statementNumber: number | null
  pageNumber: string | null
  openingBalance: number | null
  totalMoneyOut: number | null
  totalMoneyIn: number | null
  closingBalance: number | null
}

interface StatementMeta {
  signedOffFields: string[]
}

interface StatementData {
  '//': string
  summary: StatementSummary
  transactions: Transaction[]
  validation: {
    valid: boolean
    calculatedClosing: number | null
    difference: number | null
  }
  meta: StatementMeta
}

interface DateValidationIssue {
  transactionIndex: number
  transactionDate: string
  description: string
  issue: 'after_statement' | 'before_previous'
  referenceDate: string
}

interface Statement {
  id: string
  account: string
  statementNumber: string
  sourcePath: string
  jsonPath: string
  data: StatementData
  dateValidation: {
    valid: boolean
    issues: DateValidationIssue[]
  }
  missing?: boolean
}

